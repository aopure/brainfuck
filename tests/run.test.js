import { test, expect } from 'bun:test'
import { run } from '../brainfuck'

const hello = `>++++++++[<+++++++++>-]<.>++++[<+++++++>-]<+.+++++++..+++.>>++++++[<+++++++>-]<+
+.------------.>++++++[<+++++++++>-]<+.<.+++.------.--------.>>>++++[<++++++++>-
]<+.`;

const quine = `-->+++>+>+>+>+++++>++>++>->+++>++>+>>>>>>>>>>>>>>>>->++++>>>>->+++>+++>+++>+++>+
++>+++>+>+>>>->->>++++>+>>>>->>++++>+>+>>->->++>++>++>++++>+>++>->++>++++>+>+>++
>++>->->++>++>++++>+>+>>>>>->>->>++++>++>++>++++>>>>>->>>>>+++>->++++>->->->+++>
>>+>+>+++>+>++++>>+++>->>>>>->>>++++>++>++>+>+++>->++++>>->->+++>+>+++>+>++++>>>
+++>->++++>>->->++>++++>++>++++>>++[-[->>+[>]++[<]<]>>+[>]<--[++>++++>]+[<]<<++]
>>>[>]++++>++++[--[+>+>++++<<[-->>--<<[->-<[--->>+<<[+>+++<[+>>++<<]]]]]]>+++[>+
++++++++++++++<-]>--.<<<]`.replaceAll('\n', '');

const cat = `,[.[-],]`;

test('Outputs Hello, World!', () => {
  expect(run(hello)).toBe('Hello, World!');
});

test('Outputs its own code', () => {
  expect(run(quine)).toBe(quine);
});

const inputs = ['hello', 'world', 'hehe', '', '\n'];
for(let i = 0; i < inputs.length; i++) {
  const input = inputs[i] !== '\n' ? inputs[i] : '\\n';
  test(`Cat test ${i+1} | Outputs its input (${input})`, () => {
    expect(run(cat, input)).toBe(input);
  });
}